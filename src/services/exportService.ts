import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';

export interface ReportMeta {
  title: string;
  subtitle?: string;
  generatedBy: string;
  badgeNumber: string;
}

export class ExportService {
  /**
   * Export structured tabular data to CSV
   */
  public static exportToCsv(
    filename: string,
    headers: string[],
    rows: (string | number)[][]
  ): void {
    const csvContent = [
      headers.map((h) => `"${h.replace(/"/g, '""')}"`).join(','),
      ...rows.map((row) =>
        row
          .map((cell) => {
            const val = cell !== undefined && cell !== null ? String(cell) : '';
            return `"${val.replace(/"/g, '""')}"`;
          })
          .join(',')
      ),
    ].join('\r\n');

    const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
    const link = document.createElement('a');
    const url = URL.createObjectURL(blob);
    link.setAttribute('href', url);
    link.setAttribute('download', `${filename}_${new Date().toISOString().slice(0, 10)}.csv`);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  }

  /**
   * Export formal municipal visual intelligence report to PDF
   */
  public static exportToPdf(
    filename: string,
    meta: ReportMeta,
    headers: string[],
    rows: (string | number)[][],
    summaryStats?: { label: string; value: string | number }[]
  ): void {
    const doc = new jsPDF({
      orientation: 'landscape',
      unit: 'pt',
      format: 'a4',
    });

    const primaryColor = [15, 23, 42]; // Slate-900 / Navy
    const accentColor = [37, 99, 235]; // Blue-600

    // Header Bar
    doc.setFillColor(primaryColor[0], primaryColor[1], primaryColor[2]);
    doc.rect(0, 0, doc.internal.pageSize.width, 50, 'F');

    // Title
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(16);
    doc.setTextColor(255, 255, 255);
    doc.text('AEROVIS — CITY VISUAL INTELLIGENCE COMMAND', 30, 32);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(10);
    doc.setTextColor(203, 213, 225);
    doc.text('OFFICIAL MUNICIPAL REPORT', doc.internal.pageSize.width - 180, 32);

    // Meta Block
    doc.setFontSize(14);
    doc.setTextColor(15, 23, 42);
    doc.text(meta.title.toUpperCase(), 30, 80);

    doc.setFontSize(9);
    doc.setTextColor(100, 116, 139);
    doc.text(
      `Generated by: ${meta.generatedBy} (${meta.badgeNumber}) | Date: ${new Date().toLocaleString()} | Security Classification: CONFIDENTIAL - LAW ENFORCEMENT & TRAFFIC OPS`,
      30,
      96
    );

    let startY = 115;

    // Optional Key Metrics summary cards
    if (summaryStats && summaryStats.length > 0) {
      const cardWidth = 140;
      const cardHeight = 40;
      summaryStats.forEach((stat, idx) => {
        const x = 30 + idx * (cardWidth + 15);
        doc.setFillColor(248, 250, 252);
        doc.setDrawColor(226, 232, 240);
        doc.roundedRect(x, startY, cardWidth, cardHeight, 3, 3, 'FD');

        doc.setFontSize(8);
        doc.setTextColor(100, 116, 139);
        doc.text(stat.label.toUpperCase(), x + 8, startY + 14);

        doc.setFontSize(12);
        doc.setFont('helvetica', 'bold');
        doc.setTextColor(15, 23, 42);
        doc.text(String(stat.value), x + 8, startY + 32);
      });
      startY += 55;
    }

    // Auto Table
    autoTable(doc, {
      head: [headers],
      body: rows,
      startY: startY,
      theme: 'grid',
      styles: {
        fontSize: 8,
        cellPadding: 6,
        textColor: [51, 65, 85],
        lineColor: [226, 232, 240],
      },
      headStyles: {
        fillColor: [15, 23, 42],
        textColor: [255, 255, 255],
        fontStyle: 'bold',
      },
      alternateRowStyles: {
        fillColor: [248, 250, 252],
      },
      margin: { left: 30, right: 30 },
    });

    // Footer
    const pageCount = (doc as any).internal.getNumberOfPages();
    for (let i = 1; i <= pageCount; i++) {
      doc.setPage(i);
      doc.setFontSize(8);
      doc.setTextColor(148, 163, 184);
      doc.text(
        `AEROVIS Platform | Page ${i} of ${pageCount} | Automated Municipal Audit Log Record`,
        30,
        doc.internal.pageSize.height - 18
      );
    }

    doc.save(`${filename}_${new Date().toISOString().slice(0, 10)}.pdf`);
  }
}
